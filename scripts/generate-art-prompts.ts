/** Writes docs/ART_PROMPTS.md: one anime-style image prompt + filename per card. Run: npm run art-prompts */
import { writeFileSync } from 'node:fs';
import { BASE_CARDS, SKINS } from '../src/data/cards';
import { FACTION_NAMES } from '../src/engine/score';
import { CardDef, Faction, Role } from '../src/engine/types';

const POSE: Record<Role, string> = {
  CAP: 'confident leader pose, standing tall with a determined look',
  STR: 'explosive mid-attack action pose',
  STG: 'clever thinking pose with a sly smile',
  GRD: 'strong defensive stance, ready to protect',
  TRK: 'mischievous grin, playful leaping pose',
};

const AURA: Record<Faction, string> = {
  labrats: 'electric blue tech-energy',
  heroes: 'blazing crimson hero-energy',
  villains: 'dark violet shadow-energy',
  animals: 'emerald green nature-energy',
  friends: 'warm golden sunshine-energy',
};

const STYLE =
  'anime trading card illustration, cel-shaded, bold clean linework, vibrant saturated colors, dynamic speed lines, ' +
  'character centered from the waist up, portrait orientation 5:7, no text, no logo, no card border';

function prompt(c: CardDef): string {
  const who = c.skin ? `${c.name} in their "${c.skin}" look` : c.name;
  return `${who} from ${c.show}, reimagined in a shonen anime art style, ${POSE[c.role]}, ${AURA[c.faction]} swirling in the background. ${STYLE}.`;
}

let md = `# Toonville — Card Art Prompts

> Generated by \`npm run art-prompts\`.

Each card shows a picture from the **\`art/\`** folder of the public
[PtoDari/toonville](https://github.com/PtoDari/toonville) repo, matched by **filename**.

## How to add art (from your phone)

1. Copy a prompt below into an AI image app you like (or draw/commission the art yourself).
2. Save the image as **exactly** the filename shown (\`.png\` or \`.jpg\`), e.g. \`spongebob.png\`.
3. On github.com/PtoDari/toonville, open the **art** folder → **Add file → Upload files** → commit.
4. Restart the game. The card now shows the picture.

Tips: portrait images (5:7, e.g. 1000×1400) look best; keep the face in the top half, because the bottom of the card shows the name.
Skins without their own picture automatically use the base character's art.

`;

for (const f of Object.keys(FACTION_NAMES) as Faction[]) {
  md += `\n## ${FACTION_NAMES[f]}\n\n| File | Card | Prompt |\n|---|---|---|\n`;
  for (const c of BASE_CARDS.filter((x) => x.faction === f)) md += `| \`${c.id}.png\` | ${c.name} | ${prompt(c)} |\n`;
}
md += `\n## Skins (optional — fall back to base art)\n\n| File | Card | Prompt |\n|---|---|---|\n`;
for (const c of SKINS) md += `| \`${c.id}.png\` | ${c.name} — ${c.skin} | ${prompt(c)} |\n`;

writeFileSync(new URL('../docs/ART_PROMPTS.md', import.meta.url), md);
console.log(`Wrote docs/ART_PROMPTS.md (${BASE_CARDS.length + SKINS.length} prompts)`);
